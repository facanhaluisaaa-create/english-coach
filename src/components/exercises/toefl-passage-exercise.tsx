"use client";

import { useEffect, useState } from "react";
import { z } from "zod";
import { HeadphonesIcon, Loader2Icon } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { ChoiceList } from "@/components/shared/choice-list";
import { SpeakButton } from "@/components/shared/speak-button";
import { TimerBadge } from "@/components/shared/timer-badge";
import { useCountdown, useTextToSpeech } from "@/lib/speech/use-speech";
import type { ToeflPassageContent, ToeflResponse } from "@/lib/ai/schemas";
import type { ExerciseProps } from "./types";

type C = z.infer<typeof ToeflPassageContent>;
type R = z.infer<typeof ToeflResponse>;

export function ToeflPassageExercise({ content, onSubmit, submitting, evaluation, savedResponse }: ExerciseProps<C, R>) {
  const isListening = content.task_type.startsWith("listening");
  const readOnly = Boolean(evaluation);
  const [answers, setAnswers] = useState<Record<string, number | null>>(() =>
    Object.fromEntries(content.questions.map((q) => {
      const saved = savedResponse?.answers.find((a) => a.id === q.id)?.value;
      return [q.id, saved != null && saved !== "" ? Number(saved) : null];
    })),
  );
  const [played, setPlayed] = useState(readOnly || !isListening);
  const [plays, setPlays] = useState(0);
  const { remaining, elapsed } = useCountdown(content.time_limit_seconds, !readOnly && played);
  const tts = useTextToSpeech();
  const ready = content.questions.every((q) => answers[q.id] != null);

  // Reading passages become visible immediately; listening audio must be played first.
  useEffect(() => () => tts.stop(), [tts]);

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center gap-2">
          <Badge variant="secondary">{isListening ? "Listening" : "Reading"}</Badge>
          <h3 className="font-semibold">{content.title}</h3>
        </div>
        <TimerBadge remaining={remaining} elapsed={elapsed} limit={content.time_limit_seconds} />
      </div>

      {isListening ? (
        <div className="rounded-xl border bg-muted/30 p-4">
          {content.speakers.length > 0 && (
            <p className="text-xs text-muted-foreground">
              {content.speakers.map((s) => `${s.name} (${s.role})`).join(" · ")}
            </p>
          )}
          {tts.supported ? (
            <div className="mt-3 flex flex-wrap items-center gap-3">
              <Button
                type="button"
                disabled={tts.speaking || (plays >= 1 && !readOnly)}
                onClick={async () => {
                  setPlays((p) => p + 1);
                  await tts.speak(content.passage);
                  setPlayed(true);
                }}
              >
                <HeadphonesIcon /> {plays === 0 ? "Play audio" : "Played once (as in the test)"}
              </Button>
              {tts.speaking && <Button type="button" variant="outline" onClick={tts.stop}>Stop</Button>}
              <p className="text-xs text-muted-foreground">You may take notes while listening. Audio is generated by your browser&apos;s voice.</p>
            </div>
          ) : (
            <div className="mt-3 text-sm">
              <p className="text-muted-foreground">Your browser has no speech synthesis, so the script is shown instead. Read it once, then answer.</p>
              <pre className="mt-2 whitespace-pre-wrap font-sans text-sm">{content.passage}</pre>
              {!played && <Button className="mt-3" type="button" onClick={() => setPlayed(true)}>I have read it — start</Button>}
            </div>
          )}
          {readOnly && (
            <details className="mt-3 text-sm">
              <summary className="cursor-pointer text-muted-foreground">Show transcript</summary>
              <pre className="mt-2 whitespace-pre-wrap font-sans">{content.passage}</pre>
            </details>
          )}
        </div>
      ) : (
        <article className="rounded-xl border p-4 text-[15px] leading-relaxed">
          {content.passage.split(/\n{2,}|\n/).map((p, i) => <p key={i} className={i > 0 ? "mt-3" : undefined}>{p}</p>)}
          <div className="mt-3"><SpeakButton text={content.passage} label="Read aloud" size="sm" variant="ghost" /></div>
        </article>
      )}

      <div className={`space-y-5 ${!played ? "pointer-events-none opacity-40" : ""}`} aria-disabled={!played}>
        {content.questions.map((q, i) => {
          const judged = evaluation?.per_item?.find((p) => p.id === q.id);
          return (
            <section key={q.id}>
              <p className="text-sm font-medium">{i + 1}. {q.question}</p>
              <div className="mt-2">
                <ChoiceList
                  name={`Question ${i + 1}`}
                  options={q.options}
                  value={answers[q.id]}
                  onChange={(idx) => setAnswers((a) => ({ ...a, [q.id]: idx }))}
                  disabled={readOnly || !played}
                  correctIndex={readOnly ? q.answer_index : undefined}
                />
              </div>
              {readOnly && <p className="mt-2 text-sm text-muted-foreground">{judged?.feedback ?? q.explanation}</p>}
            </section>
          );
        })}
      </div>

      <p className="text-xs text-muted-foreground"><span className="font-medium text-foreground">Strategy:</span> {content.strategy_tip}</p>

      {!readOnly && (
        <div className="flex justify-end">
          <Button
            disabled={!ready || submitting}
            onClick={() =>
              onSubmit({
                answers: content.questions.map((q) => ({ id: q.id, value: String(answers[q.id] ?? "") })),
                text: null,
                seconds_used: elapsed,
                input_mode: null,
              })
            }
          >
            {submitting && <Loader2Icon className="animate-spin" />} Submit answers
          </Button>
        </div>
      )}
    </div>
  );
}
